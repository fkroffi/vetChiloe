const { Pool } = require('pg');

if (!process.env.DATABASE_URL) {
  throw new Error('Configura DATABASE_URL con la conexión de Neon.');
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: process.env.NODE_ENV === 'production' ? { rejectUnauthorized: false } : undefined,
});

function convertirPaciente(fila) {
  if (!fila || fila.id == null) return null;
  const { rut_duenio: rutDuenio, ...paciente } = fila;
  return {
    ...paciente,
    rutDuenio,
    edad: Number(paciente.edad),
    peso: Number(paciente.peso),
  };
}

async function inicializar() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS pacientes (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nombre TEXT NOT NULL,
      especie TEXT NOT NULL,
      raza TEXT NOT NULL,
      edad NUMERIC NOT NULL CHECK (edad >= 0),
      peso NUMERIC NOT NULL CHECK (peso >= 0),
      duenio TEXT NOT NULL,
      rut_duenio TEXT,
      foto TEXT,
      numero_atencion TEXT NOT NULL UNIQUE,
      emoji TEXT NOT NULL,
      diagnostico TEXT NOT NULL,
      historial JSONB NOT NULL DEFAULT '[]'::jsonb
    )
  `);
  await pool.query('ALTER TABLE pacientes ADD COLUMN IF NOT EXISTS rut_duenio TEXT');
  await pool.query('ALTER TABLE pacientes ADD COLUMN IF NOT EXISTS foto TEXT');
}

async function comprobarConexion() {
  await pool.query('SELECT 1');
}

async function obtenerTodos() {
  const { rows } = await pool.query('SELECT * FROM pacientes ORDER BY id');
  return rows.map(convertirPaciente);
}

async function obtenerPorId(id) {
  const { rows } = await pool.query('SELECT * FROM pacientes WHERE id = $1', [id]);
  return convertirPaciente(rows[0]);
}

async function contar() {
  const { rows } = await pool.query('SELECT COUNT(*)::int AS total FROM pacientes');
  return rows[0].total;
}

async function buscar(texto) {
  const { rows } = await pool.query('SELECT * FROM buscar_pacientes($1)', [texto]);
  return rows.map(convertirPaciente);
}

async function resumenPorEspecie() {
  const { rows } = await pool.query('SELECT * FROM resumen_por_especie()');
  return rows.map((fila) => ({ ...fila, total: Number(fila.total) }));
}

async function crear(datos) {
  const { rows } = await pool.query(
    'SELECT * FROM registrar_paciente($1, $2, $3, $4, $5, $6, $7, $8, $9)',
    [
      datos.nombre, datos.especie, datos.edad, datos.diagnostico,
      datos.foto || null, datos.raza, datos.peso, datos.duenio,
      datos.rutDuenio || null,
    ],
  );
  return convertirPaciente(rows[0]);
}

async function actualizarDiagnostico(id, diagnostico) {
  const { rows } = await pool.query(
    'SELECT * FROM actualizar_diagnostico($1, $2)',
    [id, diagnostico],
  );
  return convertirPaciente(rows[0]);
}

async function actualizar(id, datos) {
  const { rows } = await pool.query(
    `UPDATE pacientes
     SET nombre = $1, especie = $2, raza = $3, edad = $4, peso = $5,
       duenio = $6, rut_duenio = $7, diagnostico = $8, emoji = $9
     WHERE id = $10
     RETURNING *`,
    [
      datos.nombre, datos.especie, datos.raza, datos.edad, datos.peso,
      datos.duenio, datos.rutDuenio || null, datos.diagnostico, datos.emoji, id,
    ],
  );
  return convertirPaciente(rows[0]);
}

module.exports = {
  inicializar,
  comprobarConexion,
  obtenerTodos,
  obtenerPorId,
  contar,
  buscar,
  resumenPorEspecie,
  crear,
  actualizar,
  actualizarDiagnostico,
};