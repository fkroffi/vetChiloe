ALTER TABLE pacientes ADD COLUMN IF NOT EXISTS rut_duenio TEXT;
ALTER TABLE pacientes ADD COLUMN IF NOT EXISTS foto TEXT;

-- Genera números de atención consecutivos y sincroniza la secuencia con los datos actuales.
CREATE SEQUENCE IF NOT EXISTS seq_atencion START 1;

SELECT setval(
  'seq_atencion',
  GREATEST(
    COALESCE(MAX(substring(numero_atencion FROM '([0-9]+)$')::BIGINT), 0) + 1,
    (SELECT last_value + CASE WHEN is_called THEN 1 ELSE 0 END FROM seq_atencion)
  ),
  FALSE
)
FROM pacientes;

CREATE OR REPLACE FUNCTION generar_numero_atencion()
RETURNS TEXT AS $$
  SELECT EXTRACT(YEAR FROM CURRENT_DATE)::TEXT || '-'
    || LPAD(contador.numero::TEXT, GREATEST(4, LENGTH(contador.numero::TEXT)), '0')
  FROM (SELECT nextval('seq_atencion') AS numero) AS contador;
$$ LANGUAGE sql VOLATILE;

-- Busca por nombre o especie sin distinguir mayúsculas.
CREATE OR REPLACE FUNCTION buscar_pacientes(p_texto TEXT)
RETURNS SETOF pacientes AS $$
  SELECT *
  FROM pacientes
  WHERE nombre ILIKE '%' || COALESCE(p_texto, '') || '%'
     OR especie ILIKE '%' || COALESCE(p_texto, '') || '%'
  ORDER BY nombre;
$$ LANGUAGE sql STABLE;

-- Registra las columnas del modelo actual y deja que PostgreSQL asigne el número.
CREATE OR REPLACE FUNCTION registrar_paciente(
  p_nombre TEXT,
  p_especie TEXT,
  p_edad NUMERIC,
  p_diagnostico TEXT,
  p_foto TEXT,
  p_raza TEXT,
  p_peso NUMERIC,
  p_duenio TEXT,
  p_rut_duenio TEXT
) RETURNS pacientes AS $$
  INSERT INTO pacientes (
    nombre, numero_atencion, especie, edad, diagnostico, foto,
    raza, peso, duenio, rut_duenio, emoji, historial
  )
  VALUES (
    TRIM(p_nombre), generar_numero_atencion(), INITCAP(TRIM(p_especie)),
    p_edad, p_diagnostico, p_foto, p_raza, p_peso, p_duenio, p_rut_duenio,
    CASE INITCAP(TRIM(p_especie))
      WHEN 'Felino' THEN '🐱'
      WHEN 'Gato' THEN '🐱'
      WHEN 'Canino' THEN '🐶'
      WHEN 'Perro' THEN '🐶'
      ELSE '🐾'
    END,
    jsonb_build_array(jsonb_build_object(
      'fecha', CURRENT_DATE::TEXT,
      'detalle', 'Paciente registrado.'
    ))
  )
  RETURNING *;
$$ LANGUAGE sql VOLATILE;

-- Resume la cantidad de pacientes por especie.
CREATE OR REPLACE FUNCTION resumen_por_especie()
RETURNS TABLE (especie TEXT, total BIGINT) AS $$
  SELECT p.especie, COUNT(*)
  FROM pacientes p
  GROUP BY p.especie
  ORDER BY COUNT(*) DESC;
$$ LANGUAGE sql STABLE;

-- Conserva el diagnóstico anterior antes de actualizar la ficha.
CREATE TABLE IF NOT EXISTS historial_diagnosticos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id BIGINT NOT NULL REFERENCES pacientes(id),
  diagnostico_anterior TEXT,
  fecha TIMESTAMP NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE FUNCTION actualizar_diagnostico(
  p_id BIGINT,
  p_nuevo TEXT
) RETURNS pacientes AS $$
DECLARE
  paciente_actual pacientes;
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pacientes WHERE id = p_id) THEN
    RETURN NULL;
  END IF;

  INSERT INTO historial_diagnosticos (paciente_id, diagnostico_anterior)
  SELECT id, diagnostico FROM pacientes WHERE id = p_id;

  UPDATE pacientes
  SET diagnostico = p_nuevo
  WHERE id = p_id
  RETURNING * INTO paciente_actual;

  RETURN paciente_actual;
END;
$$ LANGUAGE plpgsql VOLATILE;

